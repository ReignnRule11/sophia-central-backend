import { Injectable } from '@nestjs/common';
import OpenAI from 'openai';

@Injectable()
export class OpenAiService {
  private readonly client: OpenAI | null;

  constructor() {
    const apiKey = process.env.OPENAI_API_KEY;
    this.client = apiKey ? new OpenAI({ apiKey }) : null;
  }

  async generateText(prompt: string, context?: string): Promise<string> {
    if (!this.client) {
      return this.getFallbackResponse(prompt, context);
    }

    try {
      const completion = await this.client.chat.completions.create({
        model: process.env.OPENAI_MODEL || 'gpt-4o-mini',
        messages: [
          {
            role: 'system',
            content:
              'You are an academic study assistant for a platform called Sophis Central. Answer with clarity, cite concepts accurately, and remain helpful for students in higher education.',
          },
          {
            role: 'user',
            content: context ? `${context}\n\nQuestion: ${prompt}` : prompt,
          },
        ],
        temperature: 0.2,
      });

      return completion.choices[0]?.message?.content || this.getFallbackResponse(prompt, context);
    } catch {
      return this.getFallbackResponse(prompt, context);
    }
  }

  private getFallbackResponse(prompt: string, context?: string): string {
    const base = 'This is a Sophis Central AI fallback response. In production, this content would be generated by an LLM with the student’s course context.';
    return context
      ? `${base}\n\nContext:\n${context}\n\nQuestion:\n${prompt}`
      : `${base}\n\nQuestion:\n${prompt}`;
  }
}
